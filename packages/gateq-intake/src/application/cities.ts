/** The region a phrase names ("somewhere in Europe" → "Europe"), or null. */
export function regionIn(words: string): string | null {
  const said = ` ${words.toLowerCase().replace(/[^a-z\s-]/gu, " ")} `;
  const region = REGIONS.find((name) => said.includes(` ${name} `));
  if (region === undefined) return null;
  const upper = new Set(["mena", "gcc", "eu", "apac", "latam", "emea"]);
  return region
    .replace(/^the /u, "")
    .split(" ")
    .map((word) =>
      upper.has(word)
        ? word.toUpperCase()
        : `${word.charAt(0).toUpperCase()}${word.slice(1)}`,
    )
    .join(" ");
}
